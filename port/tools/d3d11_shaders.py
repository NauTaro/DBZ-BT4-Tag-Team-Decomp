#!/usr/bin/env python3
"""Compile the canonical GS shaders to native D3D11 Shader Model 5 bytecode.

SPIRV-Cross and D3DCompile are build tools only. Players do not need ANGLE,
OpenGL, a shader compiler, or a separate runtime download for this backend.
"""
import ctypes as c
import hashlib
import json
import os
import re
from pathlib import Path
import shutil
import subprocess
import sys
from dx12_shaders import NAMES, inputs

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def prepare(root, gen, windows, generate=False):
    if not windows:
        return
    folder = root / 'port/src/gs/generated'
    header, manifest = folder / 'shaders_d3d11.h', folder / 'shaders_d3d11.json'
    if generate:
        cross = os.environ.get('SPIRV_CROSS') or shutil.which('spirv-cross')
        if not cross or os.name != 'nt':
            raise RuntimeError('SM5 generation needs Windows D3DCompile and SPIRV_CROSS')
        compiler = c.WinDLL('d3dcompiler_47.dll', winmode=0x800)
        compile = compiler.D3DCompile
        compile.restype = c.c_long
        compile.argtypes = [c.c_void_p,c.c_size_t,c.c_char_p,c.c_void_p,c.c_void_p,c.c_char_p,c.c_char_p,c.c_uint,c.c_uint,c.POINTER(c.c_void_p),c.POINTER(c.c_void_p)]
        def blob_bytes(blob):
            v = c.cast(blob,c.POINTER(c.POINTER(c.c_void_p))).contents
            ptr = c.WINFUNCTYPE(c.c_void_p,c.c_void_p)(v[3])(blob)
            size = c.WINFUNCTYPE(c.c_size_t,c.c_void_p)(v[4])(blob)
            data = c.string_at(ptr,size)
            c.WINFUNCTYPE(c.c_ulong,c.c_void_p)(v[2])(blob)
            return data
        out = gen / 'd3d11'
        out.mkdir(parents=True, exist_ok=True)
        arrays, records = [], {}
        for name in NAMES:
            hlsl = out / (name + '.hlsl')
            cmd = [cross,str(gen/(name+'.spv')),'--hlsl','--shader-model','50','--output',str(hlsl)]
            run = subprocess.run(cmd,capture_output=True,text=True,creationflags=0x08000000)
            if run.returncode:
                raise RuntimeError(name + ': ' + run.stdout + run.stderr)
            text = hlsl.read_text()
            if name == 'outline.frag':
                # The aux mask has one mip level. Explicit LOD avoids asking
                # FXC to unroll a variable-width outline to derive gradients.
                text = re.sub(r'aux\.Sample\(_aux_sampler, ([^)]+)\)',
                              r'aux.SampleLevel(_aux_sampler, \1, 0.0f)', text)
            if 'SV_DepthLessEqual' in text or 'SV_DepthGreaterEqual' in text:
                text = text.replace('float4 gl_FragCoord : SV_Position;',
                                    'noperspective centroid float4 gl_FragCoord : SV_Position;')
            hlsl.write_text(text, newline='\n')
            source = text.encode()
            code, errors = c.c_void_p(), c.c_void_p()
            hr = compile(source,len(source),name.encode(),None,None,b'main',
                         b'vs_5_0' if name.endswith('.vert') else b'ps_5_0',
                         (1<<11)|(1<<15),0,c.byref(code),c.byref(errors))
            diagnostics = blob_bytes(errors).decode(errors='replace') if errors else ''
            if hr < 0:
                raise RuntimeError(name + ': ' + diagnostics)
            data = blob_bytes(code)
            if data[:4] != b'DXBC':
                raise RuntimeError('Invalid SM5 container: ' + name)
            (out/(name+'.dxbc')).write_bytes(data)
            stem,stage = name.split('.')
            symbol = 'k'+stem.capitalize()+stage.capitalize()+'Dxbc'
            arrays.append('static const unsigned char '+symbol+'[] = {\n'+
                          '\n'.join(','.join(str(x) for x in data[i:i+24])+',' for i in range(0,len(data),24))+'\n};\n')
            records[name] = dict(bytes=len(data),sha256=hashlib.sha256(data).hexdigest())
        # Presentation and movie scaling use a native full-screen D3D11 pass.
        source = b'''cbuffer CopyRect : register(b0) { float4 rect; };
Texture2D<float4> image : register(t0); SamplerState linearClamp : register(s0);
float4 main(float2 uv : TEXCOORD0) : SV_Target0 {
    return image.SampleLevel(linearClamp, uv * rect.xy + rect.zw, 0.0);
}'''
        code, errors = c.c_void_p(), c.c_void_p()
        hr = compile(source,len(source),b'copy',None,None,b'main',b'ps_5_0',(1<<11)|(1<<15),0,c.byref(code),c.byref(errors))
        diagnostics = blob_bytes(errors).decode(errors='replace') if errors else ''
        if hr < 0:
            raise RuntimeError(diagnostics)
        data = blob_bytes(code)
        arrays.append('static const unsigned char kCopyFragDxbc[] = {'+','.join(str(x) for x in data)+'};\n')
        header.write_text('/* Generated by port/tools/d3d11_shaders.py. Do not edit. */\n'+''.join(arrays),newline='\n')
        manifest.write_text(json.dumps(dict(source_sha256=inputs(root),generator_sha256=digest(Path(__file__)),
            spv_sha256={n:digest(gen/(n+'.spv')) for n in NAMES},header_sha256=digest(header),shaders=records),indent=2)+'\n',newline='\n')
    if not header.exists() or not manifest.exists():
        raise RuntimeError('Missing native D3D11 shaders; run d3d11_shaders.py --generate')
    record = json.loads(manifest.read_text())
    if (record['source_sha256'] != inputs(root) or record['generator_sha256'] != digest(Path(__file__)) or
        record['header_sha256'] != digest(header) or record['spv_sha256'] != {n:digest(gen/(n+'.spv')) for n in NAMES}):
        raise RuntimeError('Stale native D3D11 shaders; regenerate the checked-in SM5 bytecode')

if __name__ == '__main__':
    root = Path(__file__).resolve().parents[2]
    prepare(root,root/'port/build/gen/gs',True,'--generate' in sys.argv)
    print('Native D3D11 SM5 shaders verified')
